-- V1: baseline schema for users, documents and the pgvector store.
--
-- This migration is idempotent so it can run both on an empty database and on a development
-- database previously created by Hibernate (ddl-auto=update) and Spring AI (initialize-schema=true)
-- before Flyway was introduced.

CREATE EXTENSION IF NOT EXISTS vector;

-- ---------------------------------------------------------------------------------------------
-- users
-- ---------------------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(255) NOT NULL,
    email      VARCHAR(255) NOT NULL,
    password   VARCHAR(255) NOT NULL,
    role       VARCHAR(20)  NOT NULL DEFAULT 'USER',
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

ALTER TABLE users ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT now();
UPDATE users SET role = 'USER' WHERE role IS NULL;
ALTER TABLE users ALTER COLUMN role SET NOT NULL;
ALTER TABLE users ALTER COLUMN password SET NOT NULL;

-- Case-insensitive uniqueness; the application also normalises usernames and emails to lower case.
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_username_lower ON users (lower(username));
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_email_lower ON users (lower(email));

-- ---------------------------------------------------------------------------------------------
-- documents (previously the Hibernate-generated table "document metadata")
-- ---------------------------------------------------------------------------------------------
DO $$
BEGIN
    IF to_regclass('public."document metadata"') IS NOT NULL AND to_regclass('public.documents') IS NULL THEN
        ALTER TABLE "document metadata" RENAME TO documents;
        -- Hibernate-generated constraint names contained the old table name (with its space)
        IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'document metadata_pkey') THEN
            ALTER TABLE documents RENAME CONSTRAINT "document metadata_pkey" TO documents_pkey;
        END IF;
        IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'document metadata_status_check') THEN
            ALTER TABLE documents RENAME CONSTRAINT "document metadata_status_check" TO documents_status_check;
        END IF;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS documents (
    id            UUID PRIMARY KEY,
    owner_id      BIGINT,
    filename      VARCHAR(255) NOT NULL,
    content_type  VARCHAR(255) NOT NULL,
    file_size     BIGINT,
    total_pages   INTEGER,
    total_chunks  INTEGER,
    status        VARCHAR(20)  NOT NULL,
    error_message TEXT,
    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ
);

ALTER TABLE documents ADD COLUMN IF NOT EXISTS owner_id BIGINT;
ALTER TABLE documents ALTER COLUMN error_message TYPE TEXT;

-- Legacy timestamps were "timestamp without time zone" written in UTC.
DO $$
DECLARE
    col TEXT;
BEGIN
    FOREACH col IN ARRAY ARRAY['created_at', 'updated_at'] LOOP
        IF EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema = 'public' AND table_name = 'documents' AND column_name = col
                     AND data_type = 'timestamp without time zone') THEN
            EXECUTE format('ALTER TABLE documents ALTER COLUMN %I TYPE TIMESTAMPTZ USING %I AT TIME ZONE %L',
                           col, col, 'UTC');
        END IF;
    END LOOP;
END $$;

-- Legacy rows were uploaded before documents had owners. They cannot be attributed to a user
-- safely, so they are moved to a quarantine table instead of being deleted. Their vectors stay in
-- vector_store without an ownerId and are therefore never returned by any user-scoped search.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM documents WHERE owner_id IS NULL) THEN
        CREATE TABLE IF NOT EXISTS legacy_unowned_documents AS TABLE documents WITH NO DATA;
        INSERT INTO legacy_unowned_documents SELECT * FROM documents WHERE owner_id IS NULL;
        DELETE FROM documents WHERE owner_id IS NULL;
    END IF;
END $$;

UPDATE documents SET filename = 'document' WHERE filename IS NULL;
ALTER TABLE documents ALTER COLUMN filename SET NOT NULL;
ALTER TABLE documents ALTER COLUMN owner_id SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_documents_owner') THEN
        ALTER TABLE documents
            ADD CONSTRAINT fk_documents_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE CASCADE;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_documents_owner_created ON documents (owner_id, created_at DESC);

-- ---------------------------------------------------------------------------------------------
-- vector_store (layout expected by Spring AI's PgVectorStore; dimensions match text-embedding-3-small)
-- ---------------------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS vector_store (
    id        UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    content   TEXT,
    metadata  JSON,
    embedding VECTOR(1536)
);

CREATE INDEX IF NOT EXISTS spring_ai_vector_index ON vector_store USING hnsw (embedding vector_cosine_ops);
-- Supports the jsonpath (@@) filters Spring AI generates for ownerId / documentId.
CREATE INDEX IF NOT EXISTS ix_vector_store_metadata_path ON vector_store USING gin ((metadata::jsonb) jsonb_path_ops);
CREATE INDEX IF NOT EXISTS ix_vector_store_owner ON vector_store ((metadata ->> 'ownerId'));
CREATE INDEX IF NOT EXISTS ix_vector_store_document ON vector_store ((metadata ->> 'documentId'));
