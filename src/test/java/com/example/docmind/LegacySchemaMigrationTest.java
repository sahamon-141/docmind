package com.example.docmind;

import com.example.docmind.support.IntegrationTestBase;
import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.jdbc.autoconfigure.JdbcConnectionDetails;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Databases created before Flyway (Hibernate ddl-auto=update + Spring AI initialize-schema) must be
 * upgraded in place: table renamed, owner column added, ownerless rows quarantined rather than lost.
 */
class LegacySchemaMigrationTest extends IntegrationTestBase {

    // the Testcontainers service connection, not the placeholder values in application-test.yml
    @Autowired
    private JdbcConnectionDetails connectionDetails;

    @Test
    void upgradesHibernateEraDatabase() {
        String dbName = "legacy_" + System.nanoTime();
        jdbcTemplate.execute("CREATE DATABASE " + dbName);
        String url = connectionDetails.getJdbcUrl().replaceFirst("/[^/?]+(\\?|$)", "/" + dbName + "$1");
        DriverManagerDataSource legacy = new DriverManagerDataSource(url, connectionDetails.getUsername(), connectionDetails.getPassword());
        JdbcTemplate db = new JdbcTemplate(legacy);

        // schema exactly as the previous Hibernate/Spring AI setup generated it
        db.execute("CREATE EXTENSION IF NOT EXISTS vector");
        db.execute("""
                create table users (id bigint generated by default as identity, email varchar(255) not null unique, password varchar(255),
                  role varchar(255) check (role in ('USER','ADMIN')), username varchar(255) not null unique, primary key (id))""");
        db.execute("""
                create table "document metadata" (id uuid not null, content_type varchar(255) not null, created_at timestamp(6) not null,
                  error_message varchar(255), file_size bigint, filename varchar(255), status varchar(255) not null,
                  total_chunks integer, total_pages integer, updated_at timestamp(6), primary key (id))""");
        db.execute("CREATE TABLE vector_store (id uuid PRIMARY KEY, content text, metadata json, embedding vector(1536))");
        db.update("insert into users(email,password,role,username) values ('old@example.com','x','USER','old')");
        db.update("""
                insert into "document metadata" values ('11111111-1111-1111-1111-111111111111','application/pdf',
                  '2026-01-01 10:00:00',null,1234,'old.pdf','INDEXED',3,1,null)""");

        Flyway.configure().dataSource(legacy).locations("classpath:db/migration")
                .baselineOnMigrate(true).baselineVersion("0").load().migrate();

        assertThat(db.queryForObject("select to_regclass('public.documents') is not null", Boolean.class)).isTrue();
        assertThat(db.queryForObject("select to_regclass('public.\"document metadata\"') is null", Boolean.class)).isTrue();
        assertThat(db.queryForObject("select count(*) from documents", Integer.class)).isZero();
        assertThat(db.queryForObject("select filename from legacy_unowned_documents", String.class)).isEqualTo("old.pdf");
        Map<String, Object> ownerColumn = db.queryForMap(
                "select is_nullable, data_type from information_schema.columns where table_name='documents' and column_name='owner_id'");
        assertThat(ownerColumn).containsEntry("is_nullable", "NO").containsEntry("data_type", "bigint");
        assertThat(db.queryForObject(
                "select data_type from information_schema.columns where table_name='documents' and column_name='created_at'", String.class))
                .isEqualTo("timestamp with time zone");
        assertThat(db.queryForObject("select count(*) from pg_constraint where conname like '% %'", Integer.class)).isZero();
        assertThat(db.queryForObject("select count(*) from users where username = 'old'", Integer.class)).isEqualTo(1);
    }
}
